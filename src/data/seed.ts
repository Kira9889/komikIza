export function buildSeedChapters(mangaId: string): Chapter[] {
  const manga = seedManga.find(m => m.id === mangaId)
  if (!manga) return []
  const total = Math.floor(Math.random() * 30) + 5
  const chapters: Chapter[] = []
  for (let i = 1; i <= total; i++) {
    chapters.push({
      id: `ch-${mangaId}-${i}`,
      manga_id: mangaId,
      name: `Chapter ${i}`,
      type: 'chapter',
      sort_order: i,
      release_timestamp: 1720000000 - i * 86400 * 3,
      pages: Array.from({ length: 8 + Math.floor(Math.random() * 12) }, (_, j) => ({
        id: `pg-${mangaId}-${i}-${j}`,
        url: `https://placehold.co/800x1200/1a1a2e/ffffff?text=${manga.title.replace(/ /g, '+')}+Ch${i}+P${j + 1}`,
        label: `Page ${j + 1}`,
      })),
    })
  }
  return chapters
}